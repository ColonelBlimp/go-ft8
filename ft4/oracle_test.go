// TestEncodeStandardMessageJT9Oracle synthesizes the encoded frame using the
// WSJT-X 3.0.2 gen_ft4wave equations and asks a pinned jt9 binary to decode it.
// It is opt-in because the external GPL oracle is not a repository dependency.
func TestEncodeStandardMessageJT9Oracle(t *testing.T) {
	jt9 := os.Getenv("WSJTX_JT9")
	if jt9 == "" {
		t.Skip("set WSJTX_JT9 to a pinned WSJT-X jt9 binary")
	}

	for _, message := range []string{
		"CQ TEST K1ABC FN42",
		"K1ABC W9XYZ -13",
		"W9XYZ K1ABC R-11",
		"K1ABC W9XYZ RR73",
		"K1ABC W9XYZ 6A WI",
		"CQ PJ4/NA2AA",
	} {
		t.Run(message, func(t *testing.T) {
			encoded, err := EncodeStandardMessage(message)
			if err != nil {
				t.Fatal(err)
			}
			samples := synthesizeOracleWave(encoded.Tones, 1500)
			dir := t.TempDir()
			wav := filepath.Join(dir, "000000_000001.wav")
			if err := writePCM16WAV(wav, samples); err != nil {
				t.Fatal(err)
			}

			cmd := exec.Command(jt9, "-5", "-d", "1", "-a", dir, "-t", dir, wav)
			output, err := cmd.CombinedOutput()
			if err != nil {
				t.Fatalf("jt9 failed: %v\n%s", err, output)
			}
			if !strings.Contains(string(output), message) {
				t.Fatalf("jt9 did not decode %q:\n%s", message, output)
			}
		})
	}
}

func synthesizeOracleWave(tones [ToneSymbols]uint8, f0 float64) []int16 {
	const (
		workingSamples = 21 * 3456
		waveSamples    = (ToneSymbols + 2) * SamplesPerSymbol
	)

	pulse := make([]float64, 3*SamplesPerSymbol)
	c := math.Pi * math.Sqrt(2/math.Log(2))
	for i := range pulse {
		t := (float64(i+1) - 1.5*SamplesPerSymbol) / SamplesPerSymbol
		pulse[i] = 0.5 * (math.Erf(c*(t+0.5)) - math.Erf(c*(t-0.5)))
	}

	dphi := make([]float64, waveSamples)
	peak := 2 * math.Pi / SamplesPerSymbol
	for symbol, tone := range tones {
		start := symbol * SamplesPerSymbol
		for i, value := range pulse {
			dphi[start+i] += peak * value * float64(tone)
		}
	}

	wave := make([]float64, waveSamples)
	phase := 0.0
	carrierStep := 2 * math.Pi * f0 / SampleRate
	for i := range wave {
		wave[i] = math.Cos(phase)
		phase = math.Mod(phase+dphi[i]+carrierStep, 2*math.Pi)
	}
	for i := 0; i < SamplesPerSymbol; i++ {
		wave[i] *= (1 - math.Cos(math.Pi*float64(i)/SamplesPerSymbol)) / 2
		last := (ToneSymbols+1)*SamplesPerSymbol + i
		wave[last] *= (1 + math.Cos(math.Pi*float64(i)/SamplesPerSymbol)) / 2
	}

	peakAmplitude := 0.0
	for _, sample := range wave {
		peakAmplitude = math.Max(peakAmplitude, math.Abs(sample))
	}
	scale := 32766.9 / peakAmplitude
	// WSJT-X ft4sim places the waveform so nominal sync begins 0.5 seconds
	// into its 72,576-sample decoder working buffer, accounting for the leading
	// ramp interval generated by gen_ft4wave.
	start := SampleRate/2 - SamplesPerSymbol
	out := make([]int16, workingSamples)
	for i, sample := range wave {
		if start+i >= len(out) {
			break
		}
		out[start+i] = int16(math.Round(scale * sample))
	}
	return out
}

func writePCM16WAV(path string, samples []int16) error {
	var wav bytes.Buffer
	dataBytes := uint32(2 * len(samples))
	wav.WriteString("RIFF")
	_ = binary.Write(&wav, binary.LittleEndian, uint32(36)+dataBytes)
	wav.WriteString("WAVEfmt ")
	_ = binary.Write(&wav, binary.LittleEndian, uint32(16))
	_ = binary.Write(&wav, binary.LittleEndian, uint16(1))
	_ = binary.Write(&wav, binary.LittleEndian, uint16(1))
	_ = binary.Write(&wav, binary.LittleEndian, uint32(SampleRate))
	_ = binary.Write(&wav, binary.LittleEndian, uint32(2*SampleRate))
	_ = binary.Write(&wav, binary.LittleEndian, uint16(2))
	_ = binary.Write(&wav, binary.LittleEndian, uint16(16))
	wav.WriteString("data")
	_ = binary.Write(&wav, binary.LittleEndian, dataBytes)
	for _, sample := range samples {
		_ = binary.Write(&wav, binary.LittleEndian, sample)
	}
	return os.WriteFile(path, wav.Bytes(), 0o600)
}
